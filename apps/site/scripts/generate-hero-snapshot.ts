import { execFileSync } from "node:child_process";
import { mkdir, readFile, rename, rm, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { runScenario, type SimulationState } from "@paneform/layout-browser";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const outputPath = resolve(root, "src/lib/hero/generated-hero-state.ts");
const scenarioPath = resolve(root, "src/lib/play/hero.scenario.json");

const renderModule = (state: SimulationState): string =>
  `// Generated by scripts/generate-hero-snapshot.ts. Do not edit.\n` +
  `import type { SimulationState } from "@paneform/layout-browser";\n\n` +
  `export const generatedHeroState = ${JSON.stringify(state, null, 2)} satisfies SimulationState;\n`;

const formatModule = (source: string): string =>
  execFileSync("oxfmt", ["--stdin-filepath", outputPath], {
    encoding: "utf8",
    input: source,
  });

async function generate(): Promise<void> {
  const scenario: unknown = JSON.parse(await readFile(scenarioPath, "utf8"));
  const state = await runScenario(scenario);
  const output = formatModule(renderModule(state));
  const current = await readFile(outputPath, "utf8").catch(() => null);
  if (current === output) return;

  await mkdir(dirname(outputPath), { recursive: true });
  const temporaryPath = `${outputPath}.${process.pid}.tmp`;
  try {
    await writeFile(temporaryPath, output, { encoding: "utf8", flag: "wx" });
    await rename(temporaryPath, outputPath);
  } finally {
    await rm(temporaryPath, { force: true });
  }
}

await generate();
